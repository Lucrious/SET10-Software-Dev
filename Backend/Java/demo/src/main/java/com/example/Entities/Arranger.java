package com.example.Entities;

public class Arranger {
    private String arrangorID;
    private String tittel;
    private String gate;
    private String gatenr;
    private String postnr;

    public String getArrangorID() {
        return arrangorID;
    }

    public void setArrangorID(String arrangorID) {
        this.arrangorID = arrangorID;
    }

    public String getTittel() {
        return tittel;
    }

    public void setTittel(String tittel) {
        this.tittel = tittel;
    }

    public String getGate() {
        return gate;
    }

    public void setGate(String gate) {
        this.gate = gate;
    }

    public String getGatenr() {
        return gatenr;
    }

    public void setGatenr(String gatenr) {
        this.gatenr = gatenr;
    }

    public String getPostnr() {
        return postnr;
    }

    public void setPostnr(String postnr) {
        this.postnr = postnr;
    }
}
